"""Convert a 128x64 PNG into a C++ header holding one display frame in SSD1306
page order (8 pages of 128 column bytes, bit 0 at the top), the format
fy_board_display_flush() sends. Pixels at least half bright (and opaque) are
lit. Needs only the Python standard library.

    python tools/frame_from_png.py components/fy_ui/splash.png components/fy_ui/include/splash_frame.h kSplashFrame
"""

import argparse
import struct
import sys
import zlib

WIDTH, HEIGHT = 128, 64
CHANNELS = {0: 1, 2: 3, 3: 1, 4: 2, 6: 4}  # PNG colour type: samples per pixel


def read_png(path):
    """Returns (width, height, rows of (luminance 0-255, alpha 0-255))."""
    data = open(path, "rb").read()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        sys.exit(f"{path}: not a PNG")
    chunks, pos = {}, 8
    idat = b""
    while pos < len(data):
        length, kind = struct.unpack(">I4s", data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + length]
        if kind == b"IDAT":
            idat += body
        else:
            chunks[kind] = body
        pos += 12 + length
    width, height, depth, ctype, _, _, interlace = struct.unpack(">IIBBBBB", chunks[b"IHDR"])
    if interlace or ctype not in CHANNELS or (depth != 8 and ctype not in (0, 3)):
        sys.exit(f"{path}: unsupported PNG (colour type {ctype}, depth {depth}, interlace {interlace})")
    palette = chunks.get(b"PLTE", b"")
    trns = chunks.get(b"tRNS", b"")
    samples = CHANNELS[ctype]
    stride = (width * samples * depth + 7) // 8
    step = max(1, samples * depth // 8)  # bytes per pixel for the filters
    raw = zlib.decompress(idat)
    rows, prev = [], bytearray(stride)
    for y in range(height):
        start = y * (stride + 1)
        kind, line = raw[start], bytearray(raw[start + 1:start + 1 + stride])
        for i in range(stride):
            a = line[i - step] if i >= step else 0
            b = prev[i]
            c = prev[i - step] if i >= step else 0
            if kind == 1:
                line[i] = (line[i] + a) & 0xFF
            elif kind == 2:
                line[i] = (line[i] + b) & 0xFF
            elif kind == 3:
                line[i] = (line[i] + (a + b) // 2) & 0xFF
            elif kind == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[i] = (line[i] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 0xFF
        rows.append([pixel(line, x, ctype, depth, palette, trns) for x in range(width)])
        prev = line
    return width, height, rows


def pixel(line, x, ctype, depth, palette, trns):
    if depth < 8:  # grey or palette index packed into bits
        per = 8 // depth
        v = (line[x // per] >> (8 - depth * (x % per + 1))) & ((1 << depth) - 1)
    else:
        v = None
    if ctype == 3:
        index = v if v is not None else line[x]
        r, g, b = palette[index * 3:index * 3 + 3]
        alpha = trns[index] if index < len(trns) else 255
        return (r + g + b) // 3, alpha
    if ctype == 0:
        return (v * 255 // ((1 << depth) - 1) if v is not None else line[x]), 255
    o = x * CHANNELS[ctype]
    if ctype == 4:
        return line[o], line[o + 1]
    alpha = line[o + 3] if ctype == 6 else 255
    return sum(line[o:o + 3]) // 3, alpha


def frame(rows):
    out = bytearray(WIDTH * HEIGHT // 8)
    for y, row in enumerate(rows):
        for x, (lum, alpha) in enumerate(row):
            if lum * alpha >= 128 * 255:
                out[(y // 8) * WIDTH + x] |= 1 << (y % 8)
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("png")
    ap.add_argument("header")
    ap.add_argument("name", help="C++ identifier for the frame array")
    args = ap.parse_args()
    width, height, rows = read_png(args.png)
    if (width, height) != (WIDTH, HEIGHT):
        sys.exit(f"{args.png}: {width}x{height}, expected {WIDTH}x{HEIGHT}")
    data = frame(rows)
    source = args.png.replace("\\", "/").rsplit("/", 1)[-1]
    lines = [
        "// SPDX-License-Identifier: MIT",
        "//",
        f"// Generated by tools/frame_from_png.py from {source}; do not edit.",
        "// One 128x64 frame in SSD1306 page order.",
        "",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace fy::ui {",
        "",
        f"inline constexpr uint8_t {args.name}[{len(data)}] = {{",
    ]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    lines += ["};", "", "}  // namespace fy::ui", ""]
    with open(args.header, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"wrote {args.header}: {sum(bin(b).count('1') for b in data)} of {WIDTH * HEIGHT} pixels lit")


if __name__ == "__main__":
    main()
