void Canvas::clear() { memset(buf_, 0, sizeof(buf_)); }

void Canvas::set_pixel(int x, int y, bool on) {
  if (x < 0 || x >= kWidth || y < 0 || y >= kHeight) return;
  uint8_t &b = buf_[(y / 8) * kWidth + x];
  const uint8_t mask = static_cast<uint8_t>(1u << (y % 8));
  b = on ? static_cast<uint8_t>(b | mask) : static_cast<uint8_t>(b & ~mask);
}

bool Canvas::pixel(int x, int y) const {
  if (x < 0 || x >= kWidth || y < 0 || y >= kHeight) return false;
  return (buf_[(y / 8) * kWidth + x] >> (y % 8)) & 1;
}

void Canvas::fill_rect(int x, int y, int w, int h, bool on) {
  for (int yy = y; yy < y + h; yy++) {
    for (int xx = x; xx < x + w; xx++) set_pixel(xx, yy, on);
  }
}

int Canvas::draw_text(int x, int y, const char *text, bool on) {
  if (!text) return x;
  for (; *text; text++) {
    unsigned char c = static_cast<unsigned char>(*text);
    if (c < 0x20 || c > 0x7e) c = '?';
    const uint8_t *glyph = kFont[c - 0x20];
    for (int col = 0; col < 5; col++) {
      for (int row = 0; row < 8; row++) {
        if ((glyph[col] >> row) & 1) set_pixel(x + col, y + row, on);
      }
    }
    x += kCharWidth;
  }
  return x;
}

